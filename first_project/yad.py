import time
import sys

def slow_print(text, delay=0.04):
    """Печатает текст медленно, символ за символом"""
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(delay)
    print()  # перевод строки в конце


def print_with_pause(line, pause_after=0.7):
    slow_print(line)
    time.sleep(pause_after)


