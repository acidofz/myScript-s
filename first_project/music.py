import time
import sys

def print_slow(text, delay=0.05):
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(delay)
    print()

lyrics = [
    "Ты не верь слезам — это не я плачу,",
    "Это просто дождь стучит по стеклу.",
    "Я давно уже не умею плакать,",
    "Я давно уже ничего не хочу...",
    "",
    "Но если вдруг ты вернёшься когда-нибудь,",
    "Если вдруг постучишь в мою дверь,",
    "Я открою, хотя и не жду уже,",
    "Потому что без тебя мне теперь...",
    "",
    "Пусто. Холодно. Больно. Темно.",
    "Пусто. Холодно. Больно. Темно."
]

print("\n" + "═" * 50)
print(" " * 15 + "Песня в терминале")
print("═" * 50 + "\n")

for line in lyrics:
    print_slow(line, delay=0.04)
    time.sleep(0.6)  # пауза между строками

print("\n" + "═" * 50)